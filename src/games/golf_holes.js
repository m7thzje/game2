// Kiest n holes zonder herhaling: eerst een vriendelijke, laatst een spectaculaire finale, daartussen willekeurig maar oplopend in moeilijkheid
export function pickHoles(n, rng = Math.random) {
  n = Math.max(2, n | 0);
  const shuf = (a) => { a = [...a]; for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(rng() * (i + 1)); [a[i], a[j]] = [a[j], a[i]]; } return a; };
  const first = shuf(POOL.filter((h) => h.diff <= 2))[0], last = shuf(POOL.filter((h) => h.finale))[0];
  const mids = POOL.filter((h) => h !== first && !h.finale).sort((a, b) => a.diff - b.diff || a.id - b.id);
  const k = n - 2, out = [];
  for (let i = 0; i < k; i++) { // k even grote emmers, uit elke emmer een willekeurige hole
    const a = Math.floor(i * mids.length / k), b = Math.max(a + 1, Math.floor((i + 1) * mids.length / k));
    out.push(mids[a + Math.floor(rng() * (b - a))]);
  }
  return [first, ...out].sort((a, b) => a.diff - b.diff).concat([last]);
}
