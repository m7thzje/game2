// ---- een potje samenstellen: 10 vragen, nooit dezelfde als het vorige potje ----
let lastIds = new Set();
function shuffle(a) { for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(Math.random() * (i + 1)); [a[i], a[j]] = [a[j], a[i]]; } return a; }
const mkOpts = (good, wrongs) => shuffle([{ t: good, ok: true }, ...wrongs.map((t) => ({ t, ok: false }))]);

function buzzQ(row, id, gold) {
  const [cat, q, g, ...w] = row;
  return { type: gold ? 'gold' : 'buzz', id, cat, q, opts: mkOpts(g, w), limit: clampN(6.5 + q.length * 0.05, 7, 10), gold: !!gold };
}
const clampN = (v, a, b) => Math.max(a, Math.min(b, v));
function soundQ(id, used) {
  const animal = Math.random() < 0.55;
  if (animal) {
    const pool = ANIMALS.filter((a) => !lastIds.has('s_' + a) && !used.has('s_' + a)); const list = pool.length ? pool : ANIMALS;
    const a = list[Math.floor(Math.random() * list.length)];
    return { type: 'sound', id: 's_' + a, cat: 'geluid', q: 'Welk DIER hoor je?', opts: mkOpts(a, shuffle(ANIMALS.filter((x) => x !== a)).slice(0, 3)), animal: a, limit: 11 };
  }
  const pool = SONGS.filter((s) => !lastIds.has('s_' + s[0]) && !used.has('s_' + s[0])); const list = pool.length ? pool : SONGS;
  const s = list[Math.floor(Math.random() * list.length)];
  return { type: 'sound', id: 's_' + s[0], cat: 'geluid', q: 'Welk LIEDJE hoor je?', opts: mkOpts(s[0], shuffle(SONGS.filter((x) => x !== s)).slice(0, 3).map((x) => x[0])), song: s[1], limit: 12 };
}

export function buildMatch() {
  const used = new Set();
  const pickIdx = (arr, key) => { const ok = [...arr.keys()].filter((i) => !used.has(key + i)); const fresh = ok.filter((i) => !lastIds.has(key + i)); const l = fresh.length ? fresh : ok; const i = l[Math.floor(Math.random() * l.length)]; used.add(key + i); return i; };
  // volgorde van de ronde-types: eerst een snelle, laatst de gouden; tussenin geschud (geen twee schattingen achter elkaar)
  let mid;
  do { mid = shuffle(['buzz', 'buzz', 'buzz', 'buzz', 'sound', 'estimate', 'estimate', 'order']); } while (mid.some((t, i) => t === 'estimate' && mid[i - 1] === 'estimate') || mid[0] === 'estimate');
  const types = ['buzz', ...mid, 'gold'];
  const list = types.map((t) => {
    if (t === 'buzz' || t === 'gold') { const i = pickIdx(BUZZ, 'b'); return buzzQ(BUZZ[i], 'b' + i, t === 'gold'); }
    if (t === 'sound') { const q = soundQ(null, used); used.add(q.id); return q; }
    if (t === 'estimate') { const i = pickIdx(ESTIMATE, 'e'); const [q, ans, min, max, fine, coarse, unit] = ESTIMATE[i]; return { type: 'estimate', id: 'e' + i, cat: 'schat', q, ans, min, max, fine, coarse, unit, limit: 7 }; }
    const i = pickIdx(ORDER, 'o'); const [q, items] = ORDER[i];
    // perm[p] = welk item (0 = eerste in goede volgorde) staat op schermpositie p (links, boven, rechts)
    return { type: 'order', id: 'o' + i, cat: 'volgorde', q, items, perm: shuffle([0, 1, 2]), limit: 11 };
  });
  lastIds = new Set(list.map((q) => q.id));
  return list;
}
// extra vraag voor een beslissende ronde (sudden death): snelle buzzer, nooit een eerder gebruikte
export function extraQuestion(usedIds) {
  const ok = [...BUZZ.keys()].filter((i) => !usedIds.has('b' + i)); const l = ok.length ? ok : [...BUZZ.keys()];
  const i = l[Math.floor(Math.random() * l.length)];
  return buzzQ(BUZZ[i], 'b' + i, false);
}
