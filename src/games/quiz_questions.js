const midi = (m) => 440 * Math.pow(2, (m - 69) / 12);
export function songDuration(str, bpm = 150) { return str.split(' ').reduce((a, n) => a + parseFloat(n.split(':')[1]), 0) * 60 / bpm; }
// speelt een melodie met audio.tone; geeft de duur (s) terug
export function playSong(audio, str, bpm = 150) {
  let t = 0; const beat = 60 / bpm;
  for (const n of str.split(' ')) {
    const [m, b] = n.split(':'); const d = parseFloat(b) * beat;
    if (m !== 'r') audio.tone(midi(+m), Math.max(0.1, d * 0.92), { type: 'square', vol: 0.16, delay: t, send: 0.15, filter: 2600 });
    t += d;
  }
  return t;
}
